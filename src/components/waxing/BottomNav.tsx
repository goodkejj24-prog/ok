"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { cn } from "@/lib/utils";

const navItems = [
  { href: "/waxing", label: "대시보드", icon: DashboardIcon },
  { href: "/waxing/customers", label: "고객", icon: CustomerIcon },
  { href: "/waxing/reservations", label: "예약", icon: CalendarIcon },
  { href: "/waxing/messages", label: "문자", icon: MessageIcon },
  { href: "/waxing/settings", label: "설정", icon: SettingsIcon },
];

export default function BottomNav() {
  const pathname = usePathname();

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 border-t bg-background/95 backdrop-blur supports-[backdrop-filter]:bg-background/80">
      <div className="mx-auto flex max-w-md items-center justify-around">
        {navItems.map((item) => {
          const isActive =
            item.href === "/waxing"
              ? pathname === "/waxing"
              : pathname.startsWith(item.href);
          return (
            <Link
              key={item.href}
              href={item.href}
              className={cn(
                "flex flex-1 flex-col items-center gap-0.5 py-2 text-[11px] transition-colors",
                isActive
                  ? "text-pink-600 font-semibold"
                  : "text-muted-foreground"
              )}
            >
              <item.icon className={cn("size-5", isActive && "text-pink-600")} />
              {item.label}
            </Link>
          );
        })}
      </div>
    </nav>
  );
}

